import { test, expect } from '@playwright/test';

test('long notes remain intact after save, reopening, and trash restoration in selected workspace', async ({ page }, testInfo) => {
  await page.goto('/');
  await page.screenshot({ path: testInfo.outputPath('home.png'), fullPage: true });
  await page.locator('.sidebar').getByRole('button', { name: /设置/ }).click();
  const workspaceName = page.getByPlaceholder('新工作区名称');
  await workspaceName.fill('独立测试工作区');
  await workspaceName.locator('..').getByRole('button', { name: '添加', exact: true }).click();
  const workspace = page.getByLabel('工作区筛选');
  await expect(workspace.locator('option', { hasText: '独立测试工作区' })).toHaveCount(1);
  const workspaceId = await workspace.locator('option').last().getAttribute('value');
  await workspace.selectOption(workspaceId!);
  await page.locator('.sidebar').getByRole('button', { name: /心得笔记/ }).click();
  await page.locator('.topbar').getByRole('button', { name: /新建/ }).click();
  let dialog = page.getByRole('dialog');
  const title = '长文保存回归测试';
  const content = '# 实验心得\n\n' + '记录实验步骤、原始结果与下一步改进。'.repeat(1500) + '\n完整结尾标记';
  await dialog.getByPlaceholder('给这条记录起个名字').fill(title);
  await dialog.locator('textarea.markdown-source').fill(content);
  await page.screenshot({ path: testInfo.outputPath('long-editor.png'), fullPage: true });
  await dialog.getByRole('button', { name: '创建记录', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  const row = page.locator('.record-row').filter({ hasText: title });
  await expect(row).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('saved-row.png'), fullPage: true });
  await row.getByRole('button', { name: title, exact: true }).click();
  dialog = page.getByRole('dialog');
  await expect(dialog.locator('textarea.markdown-source')).toHaveValue(content);
  await dialog.getByRole('button', { name: '关闭', exact: true }).first().click();
  await row.getByTitle('删除', { exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: '删除', exact: true }).click();
  await expect(row).toHaveCount(0);
  await page.locator('.sidebar').getByRole('button', { name: /回收站/ }).click();
  const trash = page.locator('article').filter({ hasText: title });
  await expect(trash).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('trash.png'), fullPage: true });
  await trash.getByRole('button', { name: '恢复', exact: true }).click();
  await expect(trash).toHaveCount(0);
  await page.locator('.sidebar').getByRole('button', { name: /心得笔记/ }).click();
  await page.locator('.record-row').filter({ hasText: title }).getByRole('button', { name: title, exact: true }).click();
  await expect(page.getByRole('dialog').locator('textarea.markdown-source')).toHaveValue(content);
  await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).first().click();
  await page.locator('.sidebar').getByRole('button', { name: /设置/ }).click();
  await expect(page.getByRole('heading', { name: /设置/ }).first()).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('settings.png'), fullPage: true });
});

test('calendar advances across midnight and new week without reopening the app', async ({ page }) => {
  await page.clock.install({ time: new Date(2026, 10, 15, 23, 59, 58) });
  await page.goto('/');
  await expect(page.getByText('今天是 2026-11-15', { exact: false })).toBeVisible();
  await page.locator('.sidebar').getByRole('button', { name: /日程安排/ }).click();
  await expect(page.getByLabel('跳转到日期')).toHaveValue('2026-11-15');
  await page.clock.runFor(3000);
  await expect(page.getByLabel('跳转到日期')).toHaveValue('2026-11-16');
  await page.locator('.sidebar').getByRole('button', { name: '工作台总览' }).click();
  await expect(page.getByText('今天是 2026-11-16', { exact: false })).toBeVisible();
});
